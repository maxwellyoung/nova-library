#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["fonttools==4.60.1"]
# ///
"""Convert the pinned platform SVG paths into deterministic Qt Canvas commands.

The optional build-time parser is not an application dependency. No SVG plugin,
network request, raster asset or icon font is required by the resulting theme.
"""
import hashlib
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def generate(root=ROOT):
    from fontTools.pens.recordingPen import RecordingPen
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.svgLib.path import parse_path
    from fontTools.svgLib import SVGPath

    folder = root / 'assets/platforms'
    manifest = json.loads((folder / 'sources.json').read_text())
    glyphs, bounds = {}, {}
    names = {'moveTo': 'M', 'lineTo': 'L', 'curveTo': 'C', 'qCurveTo': 'Q', 'closePath': 'Z', 'endPath': 'Z'}
    for name, item in sorted(manifest.items()):
        path = folder / item['file']
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != item['sha256']:
            raise ValueError('Platform source changed: ' + name)
        svg = ET.fromstring(raw)
        shapes = item.get('parser') == 'svg-shapes'
        if 'viewBox' in svg.attrib:
            x, y, width, height = map(float, svg.attrib['viewBox'].split())
        elif shapes:
            x, y = 0, 0
            width, height = (float(svg.attrib[k].removesuffix('px')) for k in ['width','height'])
        else:
            raise ValueError('Platform source needs a viewBox: ' + name)
        if width <= 0 or height <= 0 or (not shapes and any('transform' in e.attrib for e in svg.iter())):
            raise ValueError('Unsupported platform geometry: ' + name)
        scale = 24 / max(width, height)
        dx, dy = (24 - width * scale) / 2, (24 - height * scale) / 2
        pen = RecordingPen()
        if shapes:
            # The retained hardware sources include rectangles and nested affine transforms.
            # fontTools only reads matrix(); rewrite in memory so the pinned bytes stay intact.
            normalized = re.sub(rb'translate\(\s*([-\d.]+)\s*[, ]\s*([-\d.]+)\s*\)', rb'matrix(1,0,0,1,\1,\2)', raw)
            SVGPath.fromstring(normalized).draw(pen)
        else:
            for element in svg.iter():
                if element.tag.rsplit('}', 1)[-1] == 'path':
                    parse_path(element.attrib['d'], pen)
        commands = []
        for operation, points in pen.value:
            if operation not in names:
                raise ValueError('Unsupported platform path operation')
            flat = []
            for px, py in points:
                flat.extend([round((px - x) * scale + dx, 4), round((py - y) * scale + dy, 4)])
            command = names[operation]
            if len(flat) != {'M': 2, 'L': 2, 'C': 6, 'Q': 4, 'Z': 0}[command]:
                raise ValueError('Unsupported platform curve size')
            commands.append([command] + flat)
        if not commands:
            raise ValueError('Platform source has no paths')
        glyphs[name] = commands
        measured = BoundsPen(None)
        pen.replay(measured)
        left, top, right, bottom = measured.bounds
        bounds[name] = [round((left-x)*scale+dx,4),round((top-y)*scale+dy,4),
                        round((right-left)*scale,4),round((bottom-top)*scale,4)]
    header = '''.pragma library
// Generated by tools/make_platform_marks.py from assets/platforms/sources.json.
// Simple Icons 13.21.0: CC0-1.0; Xbox: Font Awesome Free 6.7.2,
// Copyright Fonticons, Inc., CC BY 4.0: https://creativecommons.org/licenses/by/4.0/
// Font Awesome source: https://fontawesome.com/ . Brand rights remain with owners.
// PC/DS/N64/SNES/NES/GB/GBC/GBA/Dreamcast: Libretro RetroArch assets Monochrome, CC BY 4.0.
// Console gamepad: Font Awesome Free 6.7.2, Fonticons, Inc., CC BY 4.0.
// Pinned sources and modifications: assets/platforms/sources.json and PROVENANCE.md.
// Source vectors and full collection notices are retained in assets/platforms/.
'''
    return header + 'var glyphs = ' + json.dumps(glyphs, separators=(',', ':'), sort_keys=True) + ';\nvar bounds = ' + json.dumps(bounds,separators=(',', ':'),sort_keys=True) + ''';
var KEYLINE = 0.9;
function commands(name) {
    if (name === "xbox360" || name === "xboxone" || name === "xboxseries") name = "xbox";
    return Object.prototype.hasOwnProperty.call(glyphs,name) ? glyphs[name] : null;
}
// alignX: 0 pins the mark to its slot's left edge beside a text column; default centres it.
function draw(context,name,width,height,alignX) {
    var data=commands(name);if(!data)return false;
    if (name === "xbox360" || name === "xboxone" || name === "xboxseries") name = "xbox";
    var b=bounds[name],w=width===undefined?24:width,h=height===undefined?24:height;
    // Same visual size: equal bounding-box area where the slot allows, never beyond the slot.
    var scale=Math.min(w/b[2],h/b[3],KEYLINE*Math.min(w,h)/Math.sqrt(b[2]*b[3]));
    context.save();context.translate((w-b[2]*scale)*(alignX===undefined?.5:alignX)-b[0]*scale,(h-b[3]*scale)/2-b[1]*scale);context.scale(scale,scale);
    context.beginPath();
    for(var i=0;i<data.length;i++) {
        var p=data[i];
        if(p[0]==="M")context.moveTo(p[1],p[2]);
        else if(p[0]==="L")context.lineTo(p[1],p[2]);
        else if(p[0]==="C")context.bezierCurveTo(p[1],p[2],p[3],p[4],p[5],p[6]);
        else if(p[0]==="Q")context.quadraticCurveTo(p[1],p[2],p[3],p[4]);
        else context.closePath();
    }
    context.fill();context.restore();return true;
}
'''


if __name__ == '__main__':
    (ROOT / 'theme/PlatformMarks.js').write_text(generate())
    print('Generated pinned platform paths for Qt Canvas; no runtime dependency added.')
